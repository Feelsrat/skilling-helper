"""Builds src/main/resources/com/skillinghelper/data/slayer-places.tsv, the Slayer task locations the guide uses.

The OSRS wiki can't be reached from the build environment, so this reuses data that was extracted from it:

  slayer_areas.json  from github.com/rRexhepi/slayer-sensei (BSD 2-Clause), src/main/resources. Every place, spawn
                     tile and access requirement there names its wiki source. Task ids are the game's own
                     (SLAYER_TARGET varp) and area ids are Konar's (SLAYER_AREA varp).
  Task.java          from github.com/runelite/runelite (BSD 2-Clause), the core Slayer plugin: the extra NPC names
                     that count for each task, e.g. "Chicken" for Birds.

Usage: python3 build_slayer_places.py <slayer_areas.json> <Task.java> <out.tsv> <source commit>
"""
import json
import re
import sys


def pt(p):
    return "%d,%d,%d" % tuple(p)


def access_cols(*accesses):
    finished, started, skills, notes = [], [], [], []
    for a in accesses:
        if not a:
            continue
        finished += [q for q in a.get("questsFinished", []) if q not in finished]
        started += [q for q in a.get("questsStarted", []) if q not in started]
        skills += ["%s:%d" % (k, v) for k, v in a.get("skills", {}).items()]
        if a.get("note"):
            notes.append(a["note"].strip())
    return [",".join(finished) or "-", ",".join(started) or "-", ",".join(skills) or "-",
            " ".join(notes) or "-"]


def clean(s):
    return s.replace("\t", " ").replace("\n", " ")


def main(areas_path, task_java, out_path, commit):
    d = json.load(open(areas_path))
    locs = {l["key"]: l for l in d["locations"]}
    lines = [
        "# Slayer task locations, generated by tools/slayer/build_slayer_places.py. Do not edit by hand.",
        "# Places, spawn tiles and access requirements: OSRS Wiki, as extracted by slayer-sensei "
        "(github.com/rRexhepi/slayer-sensei @ %s, BSD 2-Clause), whose data names a wiki source for each." % commit,
        "# Extra NPC names per task: RuneLite's Slayer plugin Task enum (BSD 2-Clause).",
        "# task <id> <name> | place/wild <taskId> <key> <label> <areaId> <questsFinished> <questsStarted> "
        "<skills> <note> <spots> <entrance> | names <task name> <npc names>",
        "# Places are listed best first: the wiki's recommended place, then the rest in wiki order.",
    ]
    for t in sorted(d["taskLocations"], key=lambda t: t["taskId"]):
        tid = t["taskId"]
        lines.append("task\t%d\t%s" % (tid, t["task"]))
        keys = list(t["locations"])
        rec = t.get("recommended")
        if rec in keys:
            keys.remove(rec)
            keys.insert(0, rec)
        for key in keys:
            l = locs[key]
            tt = next((x for x in l.get("tasks", []) if x["taskId"] == tid), {})
            spots = ";".join(pt(p) for p in tt.get("spots", [])) or "-"
            entrance = pt(l["entrance"]) if l.get("entrance") and l.get("entranceRoutable", True) else "-"
            if spots == "-" and entrance == "-":
                continue
            lines.append("\t".join(["place", str(tid), key, clean(l["label"]), str(l.get("areaId", 0))]
                                   + [clean(c) for c in access_cols(l.get("access"), tt.get("access"))]
                                   + [spots, entrance]))
    for w in sorted(d["wildernessTaskLocations"], key=lambda w: w["taskId"]):
        tid = w["taskId"]
        places = list(w["places"])
        rec = w.get("recommended")
        places.sort(key=lambda p: 0 if p["key"] == rec else 1)
        for p in places:
            spots = ";".join(pt(s) for s in p.get("spots", [])) or "-"
            entrance = pt(p["entrance"]) if p.get("entrance") else "-"
            if spots == "-" and entrance == "-":
                continue
            base = locs.get(p["key"], {})
            lines.append("\t".join(["wild", str(tid), p["key"], clean(p["label"]), "0"]
                                   + [clean(c) for c in access_cols(base.get("access"))] + [spots, entrance]))
        if not any(l.startswith("task\t%d\t" % tid) for l in lines):
            lines.append("task\t%d\t%s" % (tid, w["task"]))

    src = open(task_java).read()
    for m in re.finditer(r'^\s*[A-Z0-9_]+\((".*?)\),?\s*$', src, re.M):
        names = re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(1))
        if len(names) > 1:
            lines.append("names\t%s\t%s" % (names[0].lower(), ";".join(n.lower() for n in names[1:])))

    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(*sys.argv[1:5])
