	/**
	 * Starts a task. {@code index} is its done bit counted across both Varrock diary varps (32 on is the second).
	 */
	private static DiaryTask.DiaryTaskBuilder task(DiaryTier tier, int number, int index, String name, String text)
	{
		return DiaryTask.builder()
			.region(DiaryRegion.VARROCK)
			.tier(tier)
			.number(number)
			.name(name)
			.text(text)
			.varp(index < 32 ? VarPlayerID.VARROCK_ACHIEVEMENT_DIARY : VarPlayerID.VARROCK_ACHIEVEMENT_DIARY2)
			.bit(index % 32);
	}
